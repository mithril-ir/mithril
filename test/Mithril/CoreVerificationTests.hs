retarget :: Ref target -> target -> Ref target
retarget ref newTarget = ref {refTarget = newTarget}

-- | Map a mutation over each element of a OneOrTwo bundle.
onEachOf :: (a -> a) -> OneOrTwo a -> OneOrTwo a
onEachOf mutate bundle =
  case bundle of
    One only -> One (mutate only)
    Two first second -> Two (mutate first) (mutate second)

-- | Rewrite every Lookup node of a policy tree (used by the
-- coordinated identity-drift regressions to keep a forged model
-- consistent at every site the gate compares).
onPolicyLookups
  :: ( Ref RelationId
       -> OneOrTwo (N.EndpointBinding availability)
       -> N.PolicyNode availability
     )
  -> N.PolicyTerm availability
  -> N.PolicyTerm availability
onPolicyLookups rewrite = walk
  where
    walk term =
      term
        { N.policyTermNode =
            case N.policyTermNode term of
              N.LookupNode relationRef bindings -> rewrite relationRef bindings
              N.ValuePolicyNode value -> N.ValuePolicyNode value
              N.NoneNode payload -> N.NoneNode payload
              N.SomeNode value -> N.SomeNode value
              N.IsSomeNode inner -> N.IsSomeNode (walk inner)
              N.EqualNode left right -> N.EqualNode (walk left) (walk right)
              N.LessOrEqualNode ordered left right ->
                N.LessOrEqualNode ordered (walk left) (walk right)
              N.AndNode left right -> N.AndNode (walk left) (walk right)
              N.OrNode left right -> N.OrNode (walk left) (walk right)
              N.NotNode inner -> N.NotNode (walk inner)
        }

-- | Retarget every Argument reference the gate visits for the
-- changeRole obligation — in the effect bindings and payload, every
-- allow-policy operand, and the case scope term — through one
-- parameter-identity map (used by the coordinated identity-drift
-- regressions).
onEveryArgumentRef :: (ParameterId -> ParameterId) -> N.Model -> N.Model
onEveryArgumentRef remap =
  onCaseScopeTerm driftValue . onAuthenticatedBody driftPolicy driftShape
  where
    driftValue :: N.ValueTerm availability -> N.ValueTerm availability
    driftValue term =
      term
        { N.valueTermNode =
            case N.valueTermNode term of
              N.ArgumentNode ref ->
                N.ArgumentNode (retarget ref (remap (refTarget ref)))
              N.AttributeNode source attributeRef ->
                N.AttributeNode (driftValue source) attributeRef
              other -> other
        }

    driftBinding :: N.EndpointBinding availability -> N.EndpointBinding availability
    driftBinding binding =
      binding {N.endpointBindingTerm = driftValue (N.endpointBindingTerm binding)}

    driftPolicy :: N.PolicyTerm availability -> N.PolicyTerm availability
    driftPolicy term =
      term
        { N.policyTermNode =
            case N.policyTermNode term of
              N.ValuePolicyNode value -> N.ValuePolicyNode (driftValue value)
              N.LookupNode relationRef bindings ->
                N.LookupNode relationRef (onEachOf driftBinding bindings)
              N.NoneNode payload -> N.NoneNode payload
              N.SomeNode value -> N.SomeNode (driftValue value)
              N.IsSomeNode inner -> N.IsSomeNode (driftPolicy inner)
              N.EqualNode left right ->
                N.EqualNode (driftPolicy left) (driftPolicy right)
              N.LessOrEqualNode ordered left right ->
                N.LessOrEqualNode ordered (driftPolicy left) (driftPolicy right)
              N.AndNode left right ->
                N.AndNode (driftPolicy left) (driftPolicy right)
              N.OrNode left right ->
                N.OrNode (driftPolicy left) (driftPolicy right)
              N.NotNode inner -> N.NotNode (driftPolicy inner)
        }

    driftShape :: N.ActionShape 'ActorAvailable -> N.ActionShape 'ActorAvailable
    driftShape shape =
      case shape of
        N.ReadShape effectPath resultPath observed ->
          N.ReadShape effectPath resultPath (driftValue observed)
        N.CreateShape (N.CreateEntityEffect path entityRef initializers) resultPath ->
          N.CreateShape
            ( N.CreateEntityEffect
                path
                entityRef
                [ initializer
                    {N.initializerValue = driftValue (N.initializerValue initializer)}
                | initializer <- initializers
                ]
            )
            resultPath
        N.MutationShape effect resultPath ->
          N.MutationShape (driftEffect effect) resultPath

    driftEffect :: N.DoneEffect availability -> N.DoneEffect availability
    driftEffect effect =
      case effect of
        N.NoChangeEffect path -> N.NoChangeEffect path
        N.DeleteEntityEffect path target ->
          N.DeleteEntityEffect path (driftValue target)
        N.SetRelationEffect path relationRef bindings payload ->
          N.SetRelationEffect
            path
            relationRef
            (onEachOf driftBinding bindings)
            (driftValue payload)
        N.RemoveRelationEffect path relationRef bindings ->
          N.RemoveRelationEffect path relationRef (onEachOf driftBinding bindings)

onRelation0 :: (N.Relation -> N.Relation) -> N.Model -> N.Model
onRelation0 mutate model =
  model
    { N.modelRelations =
        onListIndex 0 mutate (N.modelRelations model)
    }

onEntity :: Int -> (N.Entity -> N.Entity) -> N.Model -> N.Model
onEntity index mutate model =
  model {N.modelEntities = onListIndex index mutate (N.modelEntities model)}

onEnum0 :: (N.EnumDefinition -> N.EnumDefinition) -> N.Model -> N.Model
onEnum0 mutate model =
  model {N.modelEnums = onListIndex 0 mutate (N.modelEnums model)}

onAction4 :: (N.Action -> N.Action) -> N.Model -> N.Model
onAction4 mutate model =
  model {N.modelActions = onListIndex 4 mutate (N.modelActions model)}

onGuarantee0 :: (N.Guarantee -> N.Guarantee) -> N.Model -> N.Model
onGuarantee0 mutate model =
  model {N.modelGuarantees = onListIndex 0 mutate (N.modelGuarantees model)}

onAuthority :: (N.Authority -> N.Authority) -> N.Model -> N.Model
onAuthority mutate =
  onGuarantee0 $ \guarantee ->
    case guarantee of
      N.NoSelfPrivilegeEscalationGuarantee path authority cases ->
        N.NoSelfPrivilegeEscalationGuarantee path (mutate authority) cases
      other -> other

onCase0 :: (N.EscalationCase -> N.EscalationCase) -> N.Model -> N.Model
onCase0 mutate =
  onGuarantee0 $ \guarantee ->
    case guarantee of
      N.NoSelfPrivilegeEscalationGuarantee path authority (onlyCase :| rest) ->
        N.NoSelfPrivilegeEscalationGuarantee path authority (mutate onlyCase :| rest)
      other -> other

onCaseScopeTerm
  :: (N.ValueTerm 'ActorAvailable -> N.ValueTerm 'ActorAvailable)
  -> N.Model
  -> N.Model
onCaseScopeTerm mutate =
  onCase0 $ \onlyCase ->
    onlyCase
      { N.escalationCaseScope =
          fmap
            (\binding -> binding {N.scopeBindingTerm = mutate (N.scopeBindingTerm binding)})
            (N.escalationCaseScope onlyCase)
      }

-- | Mutate the authenticated-only allow policy and action shape of
-- the changeRole action.
onAuthenticatedBody
  :: (N.PolicyTerm 'ActorAvailable -> N.PolicyTerm 'ActorAvailable)
  -> (N.ActionShape 'ActorAvailable -> N.ActionShape 'ActorAvailable)
  -> N.Model
  -> N.Model
onAuthenticatedBody onAllow onShape =
  onAction4 $ \action ->
    case N.actionBody action of
      N.AuthenticatedOnlyBody allow shape ->
        action
          { N.actionBody = N.AuthenticatedOnlyBody (onAllow allow) (onShape shape)
          }
      N.AnyPrincipalBody allow shape ->
        action {N.actionBody = N.AnyPrincipalBody allow shape}

-- | Mutate the SetRelation effect's bindings and payload term.
onSetRelation
  :: ( OneOrTwo (N.EndpointBinding 'ActorAvailable)
       -> OneOrTwo (N.EndpointBinding 'ActorAvailable)
     )
  -> (N.ValueTerm 'ActorAvailable -> N.ValueTerm 'ActorAvailable)
  -> N.Model
  -> N.Model
onSetRelation onBindings onPayload =
  onAuthenticatedBody id $ \shape ->
    case shape of
      N.MutationShape (N.SetRelationEffect path relationRef bindings payload) resultPath ->
        N.MutationShape
          (N.SetRelationEffect path relationRef (onBindings bindings) (onPayload payload))
          resultPath
      other -> other

onSubjectBindingTerm
  :: (N.ValueTerm 'ActorAvailable -> N.ValueTerm 'ActorAvailable)
  -> N.Model
  -> N.Model
onSubjectBindingTerm mutate = onSetRelation (onFirstBindingTerm mutate) id

onEffectPayloadTerm
  :: (N.ValueTerm 'ActorAvailable -> N.ValueTerm 'ActorAvailable)
  -> N.Model
  -> N.Model
onEffectPayloadTerm = onSetRelation id

onEffectBindings
  :: ( OneOrTwo (N.EndpointBinding 'ActorAvailable)
       -> OneOrTwo (N.EndpointBinding 'ActorAvailable)
     )
  -> N.Model
  -> N.Model
onEffectBindings mutate = onSetRelation mutate id

onFirstBindingTerm
  :: (N.ValueTerm availability -> N.ValueTerm availability)
  -> OneOrTwo (N.EndpointBinding availability)
  -> OneOrTwo (N.EndpointBinding availability)
onFirstBindingTerm mutate bindings =
  case bindings of
    Two first second ->
      Two
        first {N.endpointBindingTerm = mutate (N.endpointBindingTerm first)}
        second
    other -> other

-- | Mutate the stored ordered evidence of the privilege-floor
-- comparison (the first allow conjunct).
onFloorOrderedType :: (OrderedType -> OrderedType) -> N.Model -> N.Model
onFloorOrderedType mutate =
  onAuthenticatedBody
    ( \allow ->
        case N.policyTermNode allow of
          N.AndNode firstConjunct rest ->
            case N.policyTermNode firstConjunct of
              N.LessOrEqualNode ordered left right ->
                allow
                  { N.policyTermNode =
                      N.AndNode
                        firstConjunct
                          { N.policyTermNode =
                              N.LessOrEqualNode (mutate ordered) left right
                          }
                        rest
                  }
              _ -> allow
          _ -> allow
    )
    id

-- | Mutate the subject (Actor) binding term of the privilege-floor
-- lookup.
onFloorLookupSubjectTerm
  :: (N.ValueTerm 'ActorAvailable -> N.ValueTerm 'ActorAvailable)
  -> N.Model
  -> N.Model
onFloorLookupSubjectTerm mutate =
  onAuthenticatedBody
    ( \allow ->
        case N.policyTermNode allow of
          N.AndNode firstConjunct rest ->
            case N.policyTermNode firstConjunct of
              N.LessOrEqualNode ordered left right ->
                case N.policyTermNode right of
                  N.LookupNode relationRef bindings ->
                    allow
                      { N.policyTermNode =
                          N.AndNode
                            firstConjunct
                              { N.policyTermNode =
                                  N.LessOrEqualNode
                                    ordered
                                    left
                                    right
                                      { N.policyTermNode =
                                          N.LookupNode
                                            relationRef
                                            (onFirstBindingTerm mutate bindings)
                                      }
                              }
                            rest
                      }
                  _ -> allow
              _ -> allow
          _ -> allow
    )
    id

-- | One navigation step into the allow policy tree, matched against
-- the supported shape's constructors.
data PolicyStep = AndL | AndR | NotV | EqL | EqR | LeqL | LeqR | IsSomeV

-- | Apply a mutation to the sub-policy-term of the changeRole allow
-- policy selected by the step path (an unmatched step leaves the tree
-- unchanged, which the affected check would then fail loudly).
onAllowPolicyAt
  :: [PolicyStep]
  -> (N.PolicyTerm 'ActorAvailable -> N.PolicyTerm 'ActorAvailable)
  -> N.Model
  -> N.Model
onAllowPolicyAt steps mutate = onAuthenticatedBody (walk steps) id
  where
    walk [] term = mutate term
    walk (step : more) term =
      term
        { N.policyTermNode =
            case (step, N.policyTermNode term) of
              (AndL, N.AndNode left right) -> N.AndNode (walk more left) right
              (AndR, N.AndNode left right) -> N.AndNode left (walk more right)
              (NotV, N.NotNode inner) -> N.NotNode (walk more inner)
              (EqL, N.EqualNode left right) -> N.EqualNode (walk more left) right
              (EqR, N.EqualNode left right) -> N.EqualNode left (walk more right)
              (LeqL, N.LessOrEqualNode ordered left right) ->
                N.LessOrEqualNode ordered (walk more left) right
              (LeqR, N.LessOrEqualNode ordered left right) ->
                N.LessOrEqualNode ordered left (walk more right)
              (IsSomeV, N.IsSomeNode inner) -> N.IsSomeNode (walk more inner)
              (_, other) -> other
        }

setPolicyType
  :: PolicyType -> N.PolicyTerm 'ActorAvailable -> N.PolicyTerm 'ActorAvailable
setPolicyType newType term = term {N.policyTermType = newType}

setValueType
  :: ValueType -> N.ValueTerm 'ActorAvailable -> N.ValueTerm 'ActorAvailable
setValueType newType term = term {N.valueTermType = newType}

-- | Mutate the value term directly inside a Some or value-policy
-- node.
onPolicyValueTerm
  :: (N.ValueTerm 'ActorAvailable -> N.ValueTerm 'ActorAvailable)
  -> N.PolicyTerm 'ActorAvailable
  -> N.PolicyTerm 'ActorAvailable
onPolicyValueTerm mutate term =
  term
    { N.policyTermNode =
        case N.policyTermNode term of
          N.SomeNode value -> N.SomeNode (mutate value)
          N.ValuePolicyNode value -> N.ValuePolicyNode (mutate value)
          other -> other
    }

onEndpoint :: Int -> (N.Endpoint -> N.Endpoint) -> N.Relation -> N.Relation
onEndpoint index mutate relation =
  relation
    { N.relationEndpoints =
        case (index, N.relationEndpoints relation) of
          (0, Two first second) -> Two (mutate first) second
          (1, Two first second) -> Two first (mutate second)
          (0, One only) -> One (mutate only)
          (_, other) -> other
    }

onMember :: Int -> (N.EnumMember -> N.EnumMember) -> N.EnumDefinition -> N.EnumDefinition
onMember index mutate definition =
  definition
    { N.enumDefinitionValues =
        NonEmpty.fromList
          (onListIndex index mutate (NonEmpty.toList (N.enumDefinitionValues definition)))
    }

onParameter :: Int -> (N.Parameter -> N.Parameter) -> N.Action -> N.Action
onParameter index mutate action =
  action {N.actionParameters = onListIndex index mutate (N.actionParameters action)}

onListIndex :: Int -> (a -> a) -> [a] -> [a]
onListIndex index mutate values =
  [ if position == index then mutate value else value
  | (position, value) <- zip [0 ..] values
  ]

