            injected <-
              verifyModelWith
                (\_ -> writeIORef invoked True >> pure (Right ()))
                mutated
            pure
              [ check
                  ("coordinated " <> name <> " is an exact gate invariant, never supported")
                  (supportPlan mutated == Left (PlanInvariant expected))
              , check
                  ("coordinated " <> name <> " classifies through the production boundary without any checker")
                  (production == Just (Left (VerifierInvariantViolations expected)))
              , check
                  ("coordinated " <> name <> " never verifies through an injected runner")
