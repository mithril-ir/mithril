-- | A fake checker that records the materialized workspace lets the
-- test pin the exact checking-tree inventory and the embedded kernel
-- bytes without touching the hidden kernel module.
recordedWorkspaceChecks :: N.Model -> Text -> IO [Check]
recordedWorkspaceChecks baseModel goldenText =
  withScratchDirectory $ \scratch -> do
    let captureDirectory = scratch </> "capture"
    createDirectory captureDirectory
    fakeDirectory <- writeFakeChecker scratch "recording" $
      "#!/bin/sh\n\
      \if [ \"$1\" = \"--version\" ]; then echo \"Agda version 2.8.0\"; exit 0; fi\n\
      \root=''\n\
      \prev=''\n\
      \for a in \"$@\"; do\n\
      \  if [ \"$prev\" = \"-i\" ]; then root=$a; fi\n\
      \  prev=$a\n\
      \done\n\
      \cp -r \"$root\" \"$MITHRIL_TEST_CAPTURE/tree\"\n\
      \exit 0\n"
    outcome <-
      withEnvVarSet "MITHRIL_TEST_CAPTURE" captureDirectory $
        withShadowingCheckerPath fakeDirectory $
          verifyModelDirect baseModel
    treeEntries <- listDirectory (captureDirectory </> "tree")
    kernelEntries <- listDirectory (captureDirectory </> "tree" </> "Mithril")
    capturedGenerated <-
      ByteString.readFile (captureDirectory </> "tree" </> "Mithril" </> "Generated.agda")
    kernelComparisons <-
      mapM
        ( \name -> do
            repository <- ByteString.readFile ("agda/Mithril" </> name)
            captured <-
              ByteString.readFile (captureDirectory </> "tree" </> "Mithril" </> name)
            pure (name, repository == captured)
        )
        ["Base.agda", "Core.agda", "Policy.agda", "Effect.agda", "Guarantee.agda"]
    pure
      [ check
          "an accepting checker over the materialized tree yields the verified result"
          (outcome == Just (Right (VerificationVerified expectedObligation)))
      , check
          "the checking tree holds exactly the Mithril module directory"
          (treeEntries == ["Mithril"])
      , check
          "the checking tree holds exactly the five kernel modules and the generated module"
          ( orderedEntries kernelEntries
              == [ "Base.agda"
                 , "Core.agda"
                 , "Effect.agda"
                 , "Generated.agda"
                 , "Guarantee.agda"
                 , "Policy.agda"
                 ]
          )
