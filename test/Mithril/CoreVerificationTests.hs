-- | The checked theorem manifest is what removes textual theorem
-- discovery from the trust boundary, so its force is established
-- against the real Agda 2.8.0 executable: the valid artifact is
-- accepted, and surgical mutations of the generated text — a theorem
-- replaced by comments and a longer identifier carrying its name, a
-- theorem replaced by an accepted multiline string literal carrying
-- its name, a renamed declaration, a wrongly typed declaration, a
-- hole in a proof, and a coincidental same-named declaration outside
-- the inner theorem module — are each rejected.  Non-code occurrences
-- of a required name are irrelevant not because the language cannot
-- represent them — Agda 2.8.0 does accept multiline string literals
-- (the carrier control below is real accepted Agda) — but because the
-- qualified checked manifest must resolve every required theorem as a
-- real declaration of the inner theorem module at exactly its
-- required type, which no comment, string, hole, longer identifier,
-- or outer name can provide.
manifestAgdaChecks :: N.Model -> IO [Check]
manifestAgdaChecks baseModel =
  case supportPlan baseModel of
    Left _ ->
      pure
        [check "the supported fixture passes the support gate (prerequisite)" False]
    Right plan -> do
      let generated = renderObligationModule plan
          blockTextOf name =
            Text.unlines
              ( concat
                  [ renderedTheoremBlock spec
                  | spec <- requiredTheoremSpecs
                  , theoremSpecName spec == name
                  ]
              )
          targetBlock = blockTextOf "no-self-escalation"
          replaceBlock replacementLines =
            if Text.null targetBlock
              then generated
              else
                Text.replace
                  targetBlock
                  (Text.unlines replacementLines)
                  generated
          commentedMutant =
            replaceBlock
              [ ""
              , "  -- no-self-escalation :"
              , "  {- no-self-escalation {- no-self-escalation : -} -}"
              , "  no-self-escalation-extended : Set₁"
              , "  no-self-escalation-extended = Set"
              ]
          renamedMutant =
            if Text.null targetBlock
              then generated
              else
                Text.replace
                  targetBlock
                  ( Text.unlines
                      ( concat
                          [ [ if "  no-self-escalation" `Text.isPrefixOf` line
                                then "  renamed-" <> Text.drop 2 line
                                else line
                            | line <- renderedTheoremBlock spec
                            ]
                          | spec <- requiredTheoremSpecs
                          , theoremSpecName spec == "no-self-escalation"
                          ]
                      )
                  )
                  generated
          wrongTypeMutant =
            replaceBlock
              [ ""
              , "  no-self-escalation : Set₁"
              , "  no-self-escalation = Set"
              ]
          outerNameMutant =
            replaceBlock
              [ ""
              , "no-self-escalation : Set₁"
              , "no-self-escalation = Set"
              ]
          holeMutant =
            Text.replace
              "case-scope-is-scope-argument s a γ = refl"
              "case-scope-is-scope-argument s a γ = ?"
              generated
          -- The reviewer-accepted multiline string form: a literal
          -- with raw newlines, its body carrying the required name at
          -- column 0 exactly as a top-level declaration would appear.
          stringCarrierLines =
            [ ""
            , "  open import Agda.Builtin.String"
            , ""
            , "  string-carrier : String"
            , "  string-carrier = \"the required name occurs only inside this literal:"
            , "no-self-escalation :"
            , "  ∀ {s : State} → s ≡ s"
            , "no-self-escalation = refl"
            , "and never as a declaration\""
            ]
          multilineStringMutant = replaceBlock stringCarrierLines
          stringCarrierControl =
            if Text.null targetBlock
              then generated
              else
                Text.replace
                  targetBlock
                  (Text.unlines stringCarrierLines <> targetBlock)
                  generated
      controlAccepted <- realAgdaAccepts generated
      commentedAccepted <- realAgdaAccepts commentedMutant
      renamedAccepted <- realAgdaAccepts renamedMutant
      wrongTypeAccepted <- realAgdaAccepts wrongTypeMutant
      outerNameAccepted <- realAgdaAccepts outerNameMutant
      holeAccepted <- realAgdaAccepts holeMutant
      carrierControlAccepted <- realAgdaAccepts stringCarrierControl
      multilineStringAccepted <- realAgdaAccepts multilineStringMutant
      pure
        [ check
            "the no-self-escalation theorem block is rendered for the manifest mutants (prerequisite)"
            ( not (Text.null targetBlock)
                && targetBlock `Text.isInfixOf` generated
            )
        , check
            "real Agda accepts the valid manifest-bearing artifact"
            controlAccepted
        , check
            "real Agda rejects a removed theorem whose name survives only in comments and a longer identifier"
            (commentedMutant /= generated && not commentedAccepted)
        , check
            "real Agda rejects a renamed required theorem"
            (renamedMutant /= generated && not renamedAccepted)
        , check
            "real Agda rejects a required theorem at the wrong type"
            (wrongTypeMutant /= generated && not wrongTypeAccepted)
        , check
            "real Agda rejects a coincidental same-named declaration outside the theorem module"
            (outerNameMutant /= generated && not outerNameAccepted)
        , check
            "real Agda rejects a proof replaced by a hole"
            (holeMutant /= generated && not holeAccepted)
        , check
            "real Agda accepts the multiline string carrier alongside the real theorem (the string form is legal Agda 2.8.0)"
            (stringCarrierControl /= generated && carrierControlAccepted)
        , check
            "real Agda rejects a removed theorem whose name survives only inside the accepted multiline string"
            (multilineStringMutant /= generated && not multilineStringAccepted)
        ]

-- | Materialize the five repository kernel modules plus the given
-- module text into a fresh scratch tree and run the real @agda@
-- executable over it exactly as the production checker does.
realAgdaAccepts :: Text -> IO Bool
realAgdaAccepts moduleText =
  withScratchDirectory $ \scratch -> do
    let root = scratch </> "tree"
        moduleDirectory = root </> "Mithril"
    createDirectory root
    createDirectory moduleDirectory
    mapM_
      (\name -> copyFile ("agda/Mithril" </> name) (moduleDirectory </> name))
      ["Base.agda", "Core.agda", "Policy.agda", "Effect.agda", "Guarantee.agda"]
    ByteString.writeFile
      (moduleDirectory </> "Generated.agda")
      (Encoding.encodeUtf8 moduleText)
    (exitCode, _, _) <-
      readProcessWithExitCode
        "agda"
        [ "--safe"
        , "--no-libraries"
        , "--ignore-interfaces"
        , "-i"
        , root
        , root </> "Mithril" </> "Generated.agda"
        ]
        ""
    pure (exitCode == ExitSuccess)

