-- | The review's demonstrated forgeries — a drifted root allow
-- 'N.policyTermType', a duplicated ranking member, and duplicated
-- declared member identities under a superficially complete ranking
-- (declared identities [A,A] against ranked identities [A,B]) — must
-- classify as verifier-invariant violations through the pure gate and
-- through the complete production boundary, and the checker must
-- never be launched for them: with no checker on the search path at
-- all, the outcome must still be the invariant class (never
-- 'CheckerUnavailable'), and an injected runner must never fire.
forgedEvidenceChecks :: N.Model -> IO [Check]
forgedEvidenceChecks baseModel =
  withScratchDirectory $ \scratch -> do
    let emptyDirectory = scratch </> "empty"
    createDirectory emptyDirectory
    typeForgedOutcome <-
      withEnvVarSet "PATH" emptyDirectory (verifyModelDirect typeForgedModel)
    rankingForgedOutcome <-
      withEnvVarSet "PATH" emptyDirectory (verifyModelDirect rankingForgedModel)
    declarationForgedOutcome <-
      withEnvVarSet "PATH" emptyDirectory (verifyModelDirect declarationForgedModel)
    invoked <- newIORef False
    injectedType <-
      verifyModelWith
        (\_ -> writeIORef invoked True >> pure (Right ()))
        typeForgedModel
    injectedRanking <-
      verifyModelWith
        (\_ -> writeIORef invoked True >> pure (Right ()))
        rankingForgedModel
    injectedDeclaration <-
      verifyModelWith
        (\_ -> writeIORef invoked True >> pure (Right ()))
        declarationForgedModel
    runnerInvoked <- readIORef invoked
    pure
      [ check
          "a drifted root allow policy type is an exact gate invariant, never supported"
          ( supportPlan typeForgedModel
              == Left (PlanInvariant (rootTypeDrift :| []))
          )
      , check
          "a duplicated ranking member is an exact gate invariant, never supported"
          ( supportPlan rankingForgedModel
              == Left (PlanInvariant (rankingCorruption :| []))
          )
      , check
          "duplicated declared identities under a complete-looking ranking are an exact gate invariant, never supported"
          ( supportPlan declarationForgedModel
              == Left (PlanInvariant (declarationCorruption :| []))
          )
      , check
          "the drifted-type forgery classifies through the production boundary without any checker"
          ( typeForgedOutcome
              == Just (Left (VerifierInvariantViolations (rootTypeDrift :| [])))
          )
      , check
          "the duplicated-ranking forgery classifies through the production boundary without any checker"
          ( rankingForgedOutcome
              == Just
                (Left (VerifierInvariantViolations (rankingCorruption :| [])))
          )
      , check
          "the duplicated-declaration forgery classifies through the production boundary without any checker"
          ( declarationForgedOutcome
              == Just
                (Left (VerifierInvariantViolations (declarationCorruption :| [])))
          )
      , check
          "no forgery ever reaches an injected checker runner"
          ( not runnerInvoked
              && injectedType
                == Left (VerifierInvariantViolations (rootTypeDrift :| []))
              && injectedRanking
                == Left (VerifierInvariantViolations (rankingCorruption :| []))
              && injectedDeclaration
                == Left (VerifierInvariantViolations (declarationCorruption :| []))
          )
