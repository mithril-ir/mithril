        )
        driftCases
    runnerInvoked <- readIORef invoked
    pure
      ( concat caseChecks
          <> [ check
                 "no coordinated identity drift ever reaches an injected checker runner"
                 (not runnerInvoked)
             ]
      )
  where
    driftCases =
      [ ( "enum self-identity drift"
        , coordinatedEnumDrift baseModel
        , VerifierInvariantViolation
            ["guarantees", "0", "authority", "payloadOrder"]
            "this referenced enum's stored identity is not the canonical identity of its declaration position"
            :| []
        )
      , ( "relation self-identity drift"
        , coordinatedRelationDrift baseModel
        , VerifierInvariantViolation
            ["guarantees", "0", "authority", "relation"]
            "this referenced relation's stored identity is not the canonical identity of its declaration position"
            :| []
        )
      , ( "entity self-identity drift"
        , coordinatedEntityDrift baseModel
        , VerifierInvariantViolation
            ["schema", "relations", "0", "endpoints", "0", "entity"]
            "this referenced entity's stored identity is not the canonical identity of its declaration position"
            :| []
        )
      , ( "action self-identity drift"
        , coordinatedActionDrift baseModel
        , VerifierInvariantViolation
            ["guarantees", "0", "cases", "0", "action"]
            "this referenced action's stored identity is not the canonical identity of its declaration position"
            :| []
        )
      , ( "endpoint owner drift"
        , coordinatedEndpointOwnerDrift baseModel
        , endpointDriftAt ["schema", "relations", "0", "endpoints", "1"] :| []
        )
      , ( "endpoint position drift"
        , coordinatedEndpointPositionDrift baseModel
        , endpointDriftAt ["schema", "relations", "0", "endpoints", "0"]
            :| [endpointDriftAt ["schema", "relations", "0", "endpoints", "1"]]
        )
      , ( "parameter owner drift"
        , coordinatedParameterOwnerDrift baseModel
        , parameterDriftAt ["actions", "4", "parameters", "0"] :| []
        )
      , ( "parameter position drift"
        , coordinatedParameterPositionDrift baseModel
        , parameterDriftAt ["actions", "4", "parameters", "0"]
            :| [parameterDriftAt ["actions", "4", "parameters", "1"]]
        )
      ]

    endpointDriftAt path =
      VerifierInvariantViolation
        path
        "this declared endpoint's stored identity is not the canonical identity of its declaration position"

    parameterDriftAt path =
      VerifierInvariantViolation
        path
        "this declared parameter's stored identity is not the canonical identity of its declaration position"

-- | Enum self-identity drift, coordinated: the authority enum's
-- stored identity, its declared members' stored owners, its ranking's
-- member references, the privilege-floor literal's enum and value
-- references, the stored ordered evidence, every stored optional-enum
-- policy and value type the gate visits, and the payload parameter's
-- declared enum reference all drift together to a foreign enum
-- identity — while the canonical resolving references (the authority
-- payload order and the relation payload) keep naming the canonical
-- position, exactly the constellation every downstream comparison of
-- a lookup without self-identity validation would have accepted.
coordinatedEnumDrift :: N.Model -> N.Model
coordinatedEnumDrift =
  onEnum0 driftDeclaration
    . onAction4 (onParameter 2 driftParameterType)
    . onEffectPayloadTerm (setValueType foreignEnumType)
    . onFloorOrderedType (const (OptionalEnumOrderedType foreignEnum))
    . onAllowPolicyAt [AndL, LeqL] driftFloorValue
    . onAllowPolicyAt [AndL, LeqR] (setPolicyType foreignOptionalType)
    . onAllowPolicyAt [AndR, AndR, IsSomeV] (setPolicyType foreignOptionalType)
  where
    foreignEnum = EnumId 3
    foreignEnumType = EnumType foreignEnum
    foreignOptionalType = OptionalPolicyType foreignEnumType

    driftValueId (EnumValueId _ position) = EnumValueId foreignEnum position

    driftDeclaration definition =
      definition
        { N.enumDefinitionId = foreignEnum
        , N.enumDefinitionValues =
            NonEmpty.fromList
              [ valueMember {N.enumMemberId = driftValueId (N.enumMemberId valueMember)}
              | valueMember <- NonEmpty.toList (N.enumDefinitionValues definition)
              ]
        , N.enumDefinitionOrder =
            fmap
              ( \order ->
                  N.EnumOrder
                    ( NonEmpty.fromList
                        [ ranked
                            { N.rankedValueMember =
                                retarget
                                  (N.rankedValueMember ranked)
                                  (driftValueId (refTarget (N.rankedValueMember ranked)))
                            }
                        | ranked <- NonEmpty.toList (N.enumOrderRanking order)
                        ]
                    )
              )
              (N.enumDefinitionOrder definition)
        }

    driftParameterType parameter =
      parameter
        { N.parameterType =
            case N.parameterType parameter of
              N.EnumParameterType path enumRef ->
                N.EnumParameterType path (retarget enumRef foreignEnum)
              other -> other
        }

    driftFloorValue term =
      setPolicyType
        foreignOptionalType
        term
          { N.policyTermNode =
              case N.policyTermNode term of
                N.SomeNode value ->
                  N.SomeNode
                    value
                      { N.valueTermType = foreignEnumType
                      , N.valueTermNode =
                          case N.valueTermNode value of
                            N.EnumNode enumRef valueRef ->
                              N.EnumNode
                                (retarget enumRef foreignEnum)
                                (retarget valueRef (driftValueId (refTarget valueRef)))
                            other -> other
                      }
                other -> other
          }

-- | Relation self-identity drift, coordinated: the authority
-- relation's stored identity, both declared endpoints' stored owners,
-- the authority's subject and scope endpoint references, the effect
-- and both policy-lookup relation references, every endpoint binding,
-- and the case scope binding all drift together to a foreign relation
-- identity — while the authority relation reference keeps naming the
-- canonical position.
coordinatedRelationDrift :: N.Model -> N.Model
coordinatedRelationDrift =
  onRelation0 driftDeclaration
    . onAuthority driftAuthority
    . onCase0 driftCase
    . onAuthenticatedBody (onPolicyLookups driftLookup) driftShape
  where
    foreignRelation = RelationId 7

    driftEndpointId (EndpointId _ position) = EndpointId foreignRelation position

    driftDeclaration relation =
      relation
        { N.relationId = foreignRelation
        , N.relationEndpoints =
            onEachOf
              (\e -> e {N.endpointId = driftEndpointId (N.endpointId e)})
              (N.relationEndpoints relation)
        }

    driftEndpointRef ref = retarget ref (driftEndpointId (refTarget ref))

    driftAuthority authority =
      authority
        { N.authoritySubjectEndpoint =
            driftEndpointRef (N.authoritySubjectEndpoint authority)
        , N.authorityScopeEndpoint =
            fmap driftEndpointRef (N.authorityScopeEndpoint authority)
        }

    driftCase onlyCase =
      onlyCase
        { N.escalationCaseScope =
            fmap
              (\b -> b {N.scopeBindingEndpoint = driftEndpointId (N.scopeBindingEndpoint b)})
              (N.escalationCaseScope onlyCase)
        }

    driftBinding binding =
      binding
        { N.endpointBindingEndpoint =
            driftEndpointId (N.endpointBindingEndpoint binding)
        }

    driftLookup relationRef bindings =
      N.LookupNode
        (retarget relationRef foreignRelation)
        (onEachOf driftBinding bindings)

    driftShape shape =
      case shape of
        N.MutationShape (N.SetRelationEffect path relationRef bindings payload) resultPath ->
          N.MutationShape
            ( N.SetRelationEffect
                path
                (retarget relationRef foreignRelation)
                (onEachOf driftBinding bindings)
                payload
            )
            resultPath
        other -> other

-- | Entity self-identity drift, coordinated: the distinguished
-- subject entity's stored identity, the subject parameter's declared
-- entity reference, every stored Actor entity, and every stored
-- subject-reference policy and value type the gate visits drift
-- together to a foreign entity identity — while the subject
-- endpoint's entity reference keeps naming the canonical position.
coordinatedEntityDrift :: N.Model -> N.Model
coordinatedEntityDrift =
  onEntity 0 (\e -> e {N.entityId = foreignEntity})
    . onAction4 (onParameter 0 driftParameterType)
    . onSubjectBindingTerm (setValueType subjectType)
    . onFloorLookupSubjectTerm driftActorTerm
    . onAllowPolicyAt
        [AndR, AndL, NotV, EqL]
        (setPolicyType subjectPolicyType . onPolicyValueTerm driftActorTerm)
    . onAllowPolicyAt
        [AndR, AndL, NotV, EqR]
        (setPolicyType subjectPolicyType . onPolicyValueTerm (setValueType subjectType))
    . onAllowPolicyAt [AndR, AndR, IsSomeV] driftMembershipSubject
  where
    foreignEntity = EntityId 5
    subjectType = EntityRefType foreignEntity
    subjectPolicyType = ValuePolicyType subjectType

    driftParameterType parameter =
      parameter
        { N.parameterType =
            case N.parameterType parameter of
              N.EntityRefParameterType path entityRef ->
                N.EntityRefParameterType path (retarget entityRef foreignEntity)
              other -> other
        }

    driftActorTerm term =
      term
        { N.valueTermType = subjectType
        , N.valueTermNode =
            case N.valueTermNode term of
              N.ActorNode _ -> N.ActorNode foreignEntity
              other -> other
        }

    driftMembershipSubject term =
      term
        { N.policyTermNode =
            case N.policyTermNode term of
              N.LookupNode relationRef bindings ->
                N.LookupNode
                  relationRef
                  (onFirstBindingTerm (setValueType subjectType) bindings)
              other -> other
        }

-- | Action self-identity drift, coordinated: the case action's stored
-- identity, every declared parameter's stored owner, and every
-- Argument reference of the action body and the case scope term drift
-- together to a foreign action identity — while the case action
-- reference keeps naming the canonical position.
coordinatedActionDrift :: N.Model -> N.Model
coordinatedActionDrift =
  onEveryArgumentRef driftParameterId . onAction4 driftDeclaration
  where
    foreignAction = ActionId 9

    driftParameterId (ParameterId _ position) = ParameterId foreignAction position

    driftDeclaration action =
      action
        { N.actionId = foreignAction
        , N.actionParameters =
            [ parameter {N.parameterId = driftParameterId (N.parameterId parameter)}
            | parameter <- N.actionParameters action
            ]
        }

-- | Endpoint owner drift, coordinated: the declared scope endpoint's
-- stored owner, the authority's scope endpoint reference, every
-- scope-position endpoint binding, and the case scope binding drift
-- together to a foreign relation owner.
coordinatedEndpointOwnerDrift :: N.Model -> N.Model
coordinatedEndpointOwnerDrift =
  onRelation0 (onEndpoint 1 (\e -> e {N.endpointId = foreignScope}))
    . onAuthority
        ( \a ->
            a
              { N.authorityScopeEndpoint =
                  fmap (`retarget` foreignScope) (N.authorityScopeEndpoint a)
              }
        )
    . onCase0
        ( \c ->
            c
              { N.escalationCaseScope =
                  fmap
                    (\b -> b {N.scopeBindingEndpoint = foreignScope})
                    (N.escalationCaseScope c)
              }
        )
    . onEffectBindings (onEachOf driftBinding)
    . onAuthenticatedBody (onPolicyLookups driftLookup) id
  where
    foreignScope = EndpointId (RelationId 1) 1

    driftBinding binding =
      case N.endpointBindingEndpoint binding of
        EndpointId _ 1 -> binding {N.endpointBindingEndpoint = foreignScope}
        _ -> binding

    driftLookup relationRef bindings =
      N.LookupNode relationRef (onEachOf driftBinding bindings)

-- | Endpoint position drift, coordinated: the two declared endpoints'
-- stored positions are swapped, and the authority's endpoint
-- references, every endpoint binding, and the case scope binding swap
-- with them — a fully consistent relabeling whose stored positions no
-- longer agree with the declaration list.
coordinatedEndpointPositionDrift :: N.Model -> N.Model
coordinatedEndpointPositionDrift =
  onRelation0
    (\r -> r {N.relationEndpoints = onEachOf swapDeclared (N.relationEndpoints r)})
    . onAuthority
        ( \a ->
            a
              { N.authoritySubjectEndpoint = swapRef (N.authoritySubjectEndpoint a)
              , N.authorityScopeEndpoint = fmap swapRef (N.authorityScopeEndpoint a)
              }
        )
    . onCase0
        ( \c ->
            c
              { N.escalationCaseScope =
                  fmap
                    (\b -> b {N.scopeBindingEndpoint = swapId (N.scopeBindingEndpoint b)})
                    (N.escalationCaseScope c)
              }
        )
    . onEffectBindings (onEachOf swapBinding)
    . onAuthenticatedBody (onPolicyLookups swapLookup) id
  where
    swapId (EndpointId owner position) = EndpointId owner (1 - position)
    swapDeclared endpoint = endpoint {N.endpointId = swapId (N.endpointId endpoint)}
    swapRef ref = retarget ref (swapId (refTarget ref))
    swapBinding binding =
      binding {N.endpointBindingEndpoint = swapId (N.endpointBindingEndpoint binding)}
    swapLookup relationRef bindings =
      N.LookupNode relationRef (onEachOf swapBinding bindings)

-- | Parameter owner drift, coordinated: the subject parameter's
-- stored owner and every Argument reference to it drift together to a
-- foreign action owner.
coordinatedParameterOwnerDrift :: N.Model -> N.Model
coordinatedParameterOwnerDrift =
  onEveryArgumentRef remap
    . onAction4 (onParameter 0 (\p -> p {N.parameterId = foreignParameter}))
  where
    foreignParameter = ParameterId (ActionId 0) 0

    remap parameterId =
      if parameterId == ParameterId (ActionId 4) 0
        then foreignParameter
        else parameterId

-- | Parameter position drift, coordinated: the subject and scope
-- parameters' stored positions are swapped, and every Argument
-- reference swaps with them — the stored generation-relevant
-- positions no longer agree with the declaration list.
coordinatedParameterPositionDrift :: N.Model -> N.Model
coordinatedParameterPositionDrift =
  onEveryArgumentRef swapSubjectScope
    . onAction4
        ( onParameter 0 (\p -> p {N.parameterId = ParameterId (ActionId 4) 1})
            . onParameter 1 (\p -> p {N.parameterId = ParameterId (ActionId 4) 0})
        )
  where
    swapSubjectScope parameterId =
      case parameterId of
        ParameterId owner 0 -> ParameterId owner 1
        ParameterId owner 1 -> ParameterId owner 0
        other -> other

