-- | A fresh scratch directory (openTempFile-anchored like the other
-- helpers), removed afterwards with everything the action put in it.
withScratchDirectory :: (FilePath -> IO a) -> IO a
withScratchDirectory action = do
  temporaryBase <- getTemporaryDirectory
  (anchorPath, handle) <- openTempFile temporaryBase "mithril-verify-tests.txt"
  hClose handle
  let root = anchorPath ++ ".d"
  createDirectory root
  outcome <- try (action root)
  removeDirectoryRecursive root
  removeFile anchorPath
  case outcome of
    Left failure -> ioError (userError (show (failure :: SomeException)))
    Right result -> pure result

-- | Run an action with the given directory prepended to the search
-- path, so its fake @agda@ shadows any real one while the utilities
-- fake scripts call (such as @cp@) stay reachable.
withShadowingCheckerPath :: FilePath -> IO a -> IO a
withShadowingCheckerPath directory action = do
  original <- lookupEnv "PATH"
  let combined =
        case original of
          Just existing -> directory <> ":" <> existing
          Nothing -> directory
  withEnvVarSet "PATH" combined action

-- | Write an executable fake @agda@ script into a fresh subdirectory
-- of the scratch root and return that subdirectory (for PATH).
writeFakeChecker :: FilePath -> String -> String -> IO FilePath
writeFakeChecker scratch label script = do
  let directory = scratch </> label
  createDirectory directory
  let program = directory </> "agda"
  writeFile program script
  permissions <- getPermissions program
  setPermissions program (setOwnerExecutable True permissions)
  pure directory

--------------------------------------------------------------------
-- JSON mutation plumbing
--------------------------------------------------------------------

decodeValue :: ByteString -> Value
decodeValue bytes =
  case Aeson.decodeStrict bytes of
    Just value -> value
    Nothing -> Null

encodeValue :: Value -> ByteString
encodeValue = LazyByteString.toStrict . Aeson.encode

member :: Text -> Value -> Value
member name value =
  case value of
    Object members ->
      case KeyMap.lookup (Key.fromText name) members of
        Just found -> found
        Nothing -> Null
    _ -> Null

setMember :: Text -> Value -> Value -> Value
setMember name newValue value =
  case value of
    Object members -> Object (KeyMap.insert (Key.fromText name) newValue members)
    other -> other

overMember :: Text -> (Value -> Value) -> Value -> Value
overMember name mutate value =
  case value of
    Object members ->
      case KeyMap.lookup (Key.fromText name) members of
        Just old ->
          Object (KeyMap.insert (Key.fromText name) (mutate old) members)
        Nothing -> value
    other -> other

asList :: Value -> [Value]
asList value =
  case fromJSON value of
    Success values -> values
    Error _ -> []

overIndex :: Int -> (Value -> Value) -> Value -> Value
overIndex index mutate value =
  toJSON (onListIndex index mutate (asList value))

overSchemaMember :: Text -> (Value -> Value) -> Value -> Value
overSchemaMember name mutate = overMember "schema" (overMember name mutate)

overGuarantee0 :: (Value -> Value) -> Value -> Value
overGuarantee0 mutate = overMember "guarantees" (overIndex 0 mutate)

overAction4 :: (Value -> Value) -> Value -> Value
overAction4 mutate = overMember "actions" (overIndex 4 mutate)

overAllow :: (Value -> Value) -> Value -> Value
overAllow mutate = overAction4 (overMember "allow" mutate)
