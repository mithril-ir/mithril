-- | Run the production public verifier over the base model (the
-- fake-checker groups reach the real runner through the search
-- path, exactly as the executable would).
verifyModelDirect
  :: N.Model -> IO (Maybe (Either VerificationFailure VerificationResult))
verifyModelDirect model = do
  outcome <- try (verifyCoreDocument (CoreDocument model))
  pure $ case outcome of
    Left (_ :: SomeException) -> Nothing
    Right result -> Just result

