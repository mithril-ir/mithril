              == Just
                ( Left
                    ( CheckerWorkspaceFailure
                        "creating the workspace anchor failed: does not exist"
                    )
                )
          )
      , check
          "the hostile TMPDIR value appears in no rendered diagnostic"
          ( case outcome of
              Just (Left failure) ->
                let rendered =
                      renderVerifyFailure (InternalVerifierError failure)
                 in not (Text.pack hostileTemporary `Text.isInfixOf` rendered)
                      && not (Text.pack scratch `Text.isInfixOf` rendered)
              _ -> False
          )
      , check
          "the anchor-creation failure renders as pinned deterministic stderr"
          ( renderVerifyFailure
              ( InternalVerifierError
                  ( CheckerWorkspaceFailure
                      "creating the workspace anchor failed: does not exist"
                  )
              )
              == "mithril: internal Core verifier error: the isolated checking\
                 \ workspace could not be prepared or cleaned\n\
                 \  creating the workspace anchor failed: does not exist"
          )
      , check
          "representative workspace failures render with no path at all"
          ( all
              ( \operation ->
                  let rendered =
                        renderVerifyFailure
                          ( InternalVerifierError
                              ( CheckerWorkspaceFailure
                                  (operation <> " failed: permission denied")
                              )
                          )
                   in not ("/" `Text.isInfixOf` rendered)
              )
              [ "creating the workspace directory"
              , "materializing the checking tree"
              , "removing the workspace"
              ]
          )
      ]

