              == Just
                ( Left
                    ( CheckerRejected
                        "hostile\r\nmultiline \ESC[31mout\ESC[0m\nand stderr"
                    )
                )
          )
      , check
          "a signal-terminated checker classifies as the exact signal"
          (signaling == Just (Left (CheckerTerminatedBySignal 15)))
      ]
        <> fakeRunnerChecks
  where
    isUnavailable outcome =
      case outcome of
        Just (Left (CheckerUnavailable _)) -> True
        _ -> False

-- | The injected-runner seam: the orchestration is checked without
-- any process at all.
injectedRunnerChecks :: N.Model -> IO [Check]
injectedRunnerChecks baseModel = do
  received <- newIORef []
  accepted <-
    verifyModelWith
      (\moduleText -> do
         modifyIORef' received (moduleText :)
         pure (Right ()))
      baseModel
  invoked <- newIORef False
  unsupportedOutcome <-
    verifyModelWith
      (\_ -> writeIORef invoked True >> pure (Right ()))
      (withNoGuarantees baseModel)
  runnerInvoked <- readIORef invoked
  receivedModules <- readIORef received
  propagated <-
    verifyModelWith
      (\_ -> pure (Left (CheckerRejected "synthetic")))
      baseModel
  pure
    [ check
        "an accepting injected runner yields the exact verified obligation"
        (accepted == Right (VerificationVerified expectedObligation))
    , check
        "the injected runner receives exactly the generated module bytes"
        ( receivedModules
            == [ either
                   (const "")
                   renderObligationModule
                   (supportPlan baseModel)
               ]
        )
    , check
        "an unsupported model never reaches the checker runner"
        ( not runnerInvoked
            && case unsupportedOutcome of
              Right (VerificationUnsupported _) -> True
              _ -> False
        )
    , check
        "a runner failure propagates unchanged"
        (propagated == Left (CheckerRejected "synthetic"))
    ]
  where
    withNoGuarantees model = model {N.modelGuarantees = []}

