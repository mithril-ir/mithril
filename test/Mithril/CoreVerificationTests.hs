-- Group 1: the supported pipeline under the real checker
--------------------------------------------------------------------

supportedPipelineChecks :: N.Model -> IO [Check]
supportedPipelineChecks baseModel = do
  nspeBytes <- ByteString.readFile nspePath
  firstRun <- runPublicVerification nspeBytes
  secondRun <- runPublicVerification nspeBytes
  copyOutcome <- withScratchDirectory $ \scratch -> do
    let copyTarget = scratch </> "relocated-obligation.mir.json"
    copyFile nspePath copyTarget
    copiedBytes <- ByteString.readFile copyTarget
    pure (pipelineModel copiedBytes)
  pure
    [ check
        "the supported fixture verifies through the public pipeline under real Agda 2.8.0"
        (firstRun == Just (Right (VerificationVerified expectedObligation)))
    , check
        "a second complete public verification run is identical"
        (firstRun == secondRun)
    , check
        "a path-independent copy normalizes to the identical model"
        (copyOutcome == Just baseModel)
    , check
        "the path-independent copy generates byte-identical Agda"
        ( case copyOutcome of
            Just copiedModel ->
              fmap renderObligationModule (rightMaybe (supportPlan copiedModel))
                == fmap renderObligationModule (rightMaybe (supportPlan baseModel))
            _ -> False
        )
    ]

runPublicVerification
  :: ByteString
  -> IO (Maybe (Either VerificationFailure VerificationResult))
runPublicVerification bytes =
  case pipelineDocument bytes of
    Nothing -> pure Nothing
    Just document -> Just <$> verifyCoreDocument document

