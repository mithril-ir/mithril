    nonExecutableDirectory <- pure (scratch </> "nonexec")
    createDirectory nonExecutableDirectory
    writeFile (nonExecutableDirectory </> "agda") "not a program\n"
    nonExecutable <-
      withEnvVarSet "PATH" nonExecutableDirectory (verifyModelDirect baseModel)
    wrongVersionDirectory <- writeFakeChecker scratch "wrong-version" $
      "#!/bin/sh\n\
      \if [ \"$1\" = \"--version\" ]; then echo \"Agda version 2.7.0\"; exit 0; fi\n\
      \exit 1\n"
    wrongVersion <-
      withEnvVarSet "PATH" wrongVersionDirectory (verifyModelDirect baseModel)
    rejectingDirectory <- writeFakeChecker scratch "rejecting" $
      "#!/bin/sh\n\
      \if [ \"$1\" = \"--version\" ]; then echo \"Agda version 2.8.0\"; exit 0; fi\n\
      \printf 'hostile\\r\\nmultiline \\033[31mout\\033[0m\\n'\n\
      \printf 'and stderr' >&2\n\
      \exit 1\n"
    rejecting <-
      withEnvVarSet "PATH" rejectingDirectory (verifyModelDirect baseModel)
    signalingDirectory <- writeFakeChecker scratch "signaling" $
      "#!/bin/sh\n\
      \if [ \"$1\" = \"--version\" ]; then echo \"Agda version 2.8.0\"; exit 0; fi\n\
      \kill -TERM $$\n"
    signaling <-
      withEnvVarSet "PATH" signalingDirectory (verifyModelDirect baseModel)
    fakeRunnerChecks <- injectedRunnerChecks baseModel
    pure $
      [ check
          "a missing checker classifies as unavailable"
          (isUnavailable missing)
      , check
          "a non-executable checker classifies as unavailable"
          (isUnavailable nonExecutable)
      , check
          "a wrong-version checker classifies as the exact version mismatch"
          ( wrongVersion
              == Just (Left (CheckerVersionMismatch "Agda version 2.7.0"))
          )
